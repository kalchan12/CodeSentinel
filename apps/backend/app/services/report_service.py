    @classmethod
    def _build_finding_block(
        cls,
        f: Finding,
        c_critical: colors.Color,
        c_high: colors.Color,
        c_medium: colors.Color,
        c_low: colors.Color,
        c_border: colors.Color,
        c_bg_light: colors.Color,
        meta_label: ParagraphStyle,
        meta_val: ParagraphStyle,
        body_style: ParagraphStyle,
        code_snippet_style: ParagraphStyle,
        remediation_style: ParagraphStyle,
    ) -> KeepTogether:
        """Build an elegant, self-contained flowable card for a single security finding."""
        s_color = (
            c_critical
            if f.severity == "critical"
            else (
                c_high if f.severity == "high" else (c_medium if f.severity == "medium" else c_low)
            )
        )

        # Title row
        title_html = (
            f"<font color='{s_color.hexval()}'><b>[{f.severity.upper()}]</b></font> "
            f"<b>{html.escape(f.title)}</b>"
        )
        title_para = Paragraph(
            title_html,
            ParagraphStyle(
                "FTitle",
                fontName="Helvetica-Bold",
                fontSize=9.5,
                leading=13,
                textColor=colors.HexColor("#0F172A"),
            ),
        )

        rule_badge_html = (
            f"<font size='7' color='#64748B'>Rule: {html.escape(f.rule_id or 'Custom')} | "
            f"Analyzer: {html.escape(f.analyzer.capitalize())}</font>"
        )
        rule_badge = Paragraph(
            rule_badge_html,
            ParagraphStyle("FRule", fontName="Helvetica", fontSize=7.5, leading=9, alignment=2),
        )

        loc_text = f"{html.escape(f.file)}"
        if f.line_start is not None:
            loc_text += f":{f.line_start}"
            if f.line_end is not None and f.line_end != f.line_start:
                loc_text += f"-{f.line_end}"

        loc_para = Paragraph(
            f"<b>Location:</b> <font face='Courier' size='7.5'>{loc_text}</font>", body_style
        )

        card_elements: list[Any] = [
            Table(
                [[title_para, rule_badge]],
                colWidths=[360, 162],
                style=[
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("LEFTPADDING", (0, 0), (-1, -1), 0),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                    ("TOPPADDING", (0, 0), (-1, -1), 0),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                ],
            ),
            loc_para,
            Spacer(1, 3),
        ]

        if f.description:
            desc_para = Paragraph(html.escape(f.description), body_style)
            card_elements.append(desc_para)
            card_elements.append(Spacer(1, 4))

        # Code snippet block if available
        if f.code_snippet and f.code_snippet.strip():
            snippet_clean = f.code_snippet.strip()
            # Truncate overly long snippets to 8 lines for PDF readability
            lines = snippet_clean.splitlines()[:8]
            escaped_code = "<br/>".join(
                [html.escape(line).replace(" ", "&nbsp;") for line in lines]
            )
            code_table = Table([[Paragraph(escaped_code, code_snippet_style)]], colWidths=[512])
            code_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F1F5F9")),
                        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ("LEFTPADDING", (0, 0), (-1, -1), 6),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                    ]
                )
            )
            card_elements.append(code_table)
            card_elements.append(Spacer(1, 4))

        # Remediation block
        remed_text = f.remediation or (
            "Follow OWASP/CWE remediation guidelines and secure coding standards for this pattern."
        )
        remed_table = Table(
            [[Paragraph(f"<b>Remediation:</b> {html.escape(remed_text)}", remediation_style)]],
            colWidths=[512],
        )
        remed_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F5F3FF")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#DDD6FE")),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("LEFTPADDING", (0, 0), (-1, -1), 6),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ]
            )
        )
        card_elements.append(remed_table)

        outer_card = Table([[card_elements]], colWidths=[532])
        outer_card.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), colors.white),
                    ("BOX", (0, 0), (-1, -1), 0.5, c_border),
                    ("LINELEFT", (0, 0), (0, 0), 3.0, s_color),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ("LEFTPADDING", (0, 0), (-1, -1), 8),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ]
            )
        )

        return KeepTogether([outer_card])
