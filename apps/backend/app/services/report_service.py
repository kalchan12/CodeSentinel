class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and draw total page numbers and running headers."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running header on pages > 1
        if self._pageNumber > 1:
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(40, 755, 572, 755)
            self.drawString(40, 760, "CodeSentinel — Executive Security Assessment Report")
            self.drawRightString(572, 760, "CONFIDENTIAL / AUDIT-GRADE")

        # Running footer on all pages
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(40, 42, 572, 42)
        self.drawString(40, 30, "Generated by CodeSentinel Local-First Security Engine")
        self.drawRightString(572, 30, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


class ReportService:
    """Service to compute compliance and compile executive PDF reports."""

    @staticmethod
    def get_compliance_benchmarks(
        findings: list[Finding], assessment: RiskAssessment | None
    ) -> list[ComplianceStatus]:
        critical = sum(1 for f in findings if f.severity == "critical")
        high = sum(1 for f in findings if f.severity == "high")
        secret_count = sum(1 for f in findings if f.category == "secrets")
        dep_count = sum(1 for f in findings if f.category == "dependency")
        vuln_count = sum(1 for f in findings if f.category == "vulnerability")

        return [
            ComplianceStatus(
                framework="OWASP Top 10 (2021)",
                score=max(20, 100 - vuln_count * 12),
                status="compliant"
                if vuln_count == 0
                else "warning"
                if vuln_count <= 2
                else "failing",
                violations=vuln_count,
            ),
            ComplianceStatus(
                framework="CWE Top 25 Standards",
                score=max(25, 100 - (critical * 20 + high * 10)),
                status="compliant"
                if critical == 0 and high <= 1
                else "warning"
                if critical <= 1
                else "failing",
                violations=critical + high,
            ),
            ComplianceStatus(
                framework="Secret Hygiene & Credentials",
                score=max(10, 100 - secret_count * 25),
                status="compliant"
                if secret_count == 0
                else "warning"
                if secret_count == 1
                else "failing",
                violations=secret_count,
            ),
            ComplianceStatus(
                framework="SCA / Dependency Health",
                score=max(25, 100 - dep_count * 8),
                status="compliant"
                if dep_count == 0
                else "warning"
                if dep_count <= 3
                else "failing",
                violations=dep_count,
            ),
        ]

    @staticmethod
    def calculate_summary(
        scan: Scan,
        project: Project | None,
        assessment: RiskAssessment | None,
        findings: list[Finding],
    ) -> ReportSummary:
        critical = sum(1 for f in findings if f.severity == "critical")
        high = sum(1 for f in findings if f.severity == "high")
        medium = sum(1 for f in findings if f.severity == "medium")
        low = sum(1 for f in findings if f.severity == "low")

        score = round(assessment.overall_score) if assessment else 75

        if score >= 90:
            grade = "A"
        elif score >= 80:
            grade = "B+"
        elif score >= 70:
            grade = "B-"
        elif score >= 60:
            grade = "C"
        else:
            grade = "F"

        compliance = ReportService.get_compliance_benchmarks(findings, assessment)

        return ReportSummary(
            projectName=project.name if project else "Unknown Project",
            scanId=scan.id,
            generatedAt=scan.completed_at or scan.created_at or datetime.now(UTC),
            overallScore=score,
            grade=grade,
            totalFindings=len(findings) if findings else scan.findings_count,
            criticalCount=critical,
            highCount=high,
            mediumCount=medium,
            lowCount=low,
            compliance=compliance,
        )

